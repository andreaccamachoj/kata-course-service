-- ============================================================
-- USER_CHAPTER_PROGRESS
-- ============================================================
CREATE TABLE training.user_chapter_progress (
    id BIGSERIAL PRIMARY KEY,
    user_id BIGINT NOT NULL,
    chapter_id BIGINT NOT NULL,
    completed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_user_chapter_progress_chapter
        FOREIGN KEY (chapter_id) REFERENCES training.chapters (id)
        ON DELETE CASCADE
);

CREATE INDEX idx_user_chapter_progress_user_id
    ON training.user_chapter_progress (user_id);

CREATE INDEX idx_user_chapter_progress_chapter_id
    ON training.user_chapter_progress (chapter_id);

-- ============================================================
-- USER_COURSE_PROGRESS
-- ============================================================
CREATE TABLE training.user_course_progress (
    id BIGSERIAL PRIMARY KEY,
    user_id BIGINT NOT NULL,
    course_id BIGINT NOT NULL,
    progress_pct NUMERIC(5,2) DEFAULT 0.00,
    completed_at TIMESTAMP,
    CONSTRAINT fk_user_course_progress_course
        FOREIGN KEY (course_id) REFERENCES training.courses (id)
        ON DELETE CASCADE
);

CREATE UNIQUE INDEX uq_user_course_progress_user_course
    ON training.user_course_progress (user_id, course_id);

-- ============================================================
-- BADGES
-- ============================================================
CREATE TABLE training.badges (
    id BIGSERIAL PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    icon_s3_key VARCHAR(255),
    criterion VARCHAR(50) NOT NULL DEFAULT 'course_completed',
    course_id BIGINT UNIQUE, -- relación 1:1
    CONSTRAINT fk_badges_course
        FOREIGN KEY (course_id)
        REFERENCES training.courses (id)
        ON DELETE CASCADE
);

-- ============================================================
-- USER_BADGES
-- ============================================================
CREATE TABLE training.user_badges (
    id BIGSERIAL PRIMARY KEY,
    user_id BIGINT NOT NULL,
    badge_id BIGINT NOT NULL,
    course_id BIGINT,
    awarded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_user_badges_badge
        FOREIGN KEY (badge_id) REFERENCES training.badges (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_user_badges_course
        FOREIGN KEY (course_id) REFERENCES training.courses (id)
        ON DELETE SET NULL
);

CREATE UNIQUE INDEX uq_user_badges_user_badge_course